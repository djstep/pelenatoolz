/**
 * Факт по вырезанной сцене. Сцена в дне — факт пишется как есть (история съёмок).
 * Не в дне — отказ и на новую строку факта, и на правку уже сохранённой: сохранение факта
 * ставит сцену в день КПП. Невырезанные — без ограничений. Текст отказа или null.
 */
export function cutSceneFactRefusal(scene: { cut: boolean; inDay: boolean; label: string }) {
  if (!scene.cut || scene.inDay) return null;
  return `Сцена ${scene.label} вырезана — верните её в либретто, чтобы записать факт`;
}
