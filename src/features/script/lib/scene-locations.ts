/**
 * Привязки сцены к объектам после сохранения карточки. Карточка пока выбирает один объект
 * (первую привязку), а у смежной сцены их несколько («ДЕТСКАЯ / КОРИДОР»): остальные
 * сохраняются как были. Выбран объект из уже привязанных — все привязки без изменений;
 * выбран другой — он встаёт вместо первой, остальные остаются.
 */
export function keptSceneLocationIds(current: readonly string[], chosen: string): string[] {
  if (current.includes(chosen)) return [...current];
  return [chosen, ...current.slice(1)];
}
