# Скрытый ввод для команд копирования. Подключается через source, значения на экран не выводит.
# Вставка из терминала может добавить ESC-последовательности, CR и пробелы: они убираются,
# а формат проверяется до использования значения.

AGE_KEY_RE='^AGE-SECRET-KEY-1[023456789ACDEFGHJKLMNPQRSTUVWXYZ]{58}$'
HEX64_RE='^[0-9a-f]{64}$'
S3_VALUE_RE='^[[:graph:]]{8,256}$'

# Из stdin в stdout: ESC-последовательности, управляющие символы, пробелы по краям.
secret_clean() {
  LC_ALL=C sed -E 's/\x1b\[[0-9;?]*[ -\/]*[@-~]//g; s/\x1b[@-_]?//g' \
    | LC_ALL=C tr -d '\000-\010\012-\037\177' \
    | LC_ALL=C sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//'
}

_read_tty() {
  local flags=$1 var=$2 prompt=$3 raw=""
  [ -r /dev/tty ] || { echo "Нужен терминал: команда спрашивает значения вручную"; exit 1; }
  # Просим терминал не оборачивать вставку в метки.
  printf '\033[?2004l' > /dev/tty
  IFS= read -r $flags -p "$prompt" raw < /dev/tty
  [ -z "$flags" ] || printf '\n' > /dev/tty
  printf -v "$var" '%s' "$(printf '%s' "$raw" | secret_clean)"
}

# ask_secret ИМЯ "подсказка": символы на экране не появляются.
ask_secret() { _read_tty -s "$1" "$2"; }
# ask_line ИМЯ "подсказка": обычный ввод с той же очисткой.
ask_line() { _read_tty "" "$1" "$2"; }

# require_format "значение" "выражение" "что это" "что ожидается"
require_format() {
  if [[ ! "$1" =~ $2 ]]; then
    echo "$3: неверный формат (длина ${#1}). Ожидается: $4."
    echo "Значение не показано. Проверьте, что скопировано целиком, и запустите ещё раз."
    exit 1
  fi
}
